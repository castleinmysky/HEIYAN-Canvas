export function filterPromptPresets(query: string) {
  const normalized = query.trim().toLocaleLowerCase('zh-CN');
  if (!normalized) return [...promptPresets];
  return promptPresets.filter((preset) => [preset.label, preset.description, ...preset.aliases]
    .some((value) => value.toLocaleLowerCase('zh-CN').includes(normalized)));
}

export function appendPromptPreset(existingText: string, presetText: string) {
  const existing = String(existingText || '').trimEnd();
  const preset = String(presetText || '').trim();
  if (!existing) return preset;
  if (!preset) return existing;
  return `${existing}\n\n${preset}`;
}
